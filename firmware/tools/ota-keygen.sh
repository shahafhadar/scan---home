#!/usr/bin/env bash
# Creates the firmware signing key -- once, ever, for a product.
#
#   tools/ota-keygen.sh
#
# Writes the private half to ~/.scancart-signing/ota-signing-key.pem (mode
# 600, never into this repository) and the public half into
# src/ota/ota_public_key.h, which is compiled into every image.
#
# It refuses to run when a key already exists. Every device in the field
# trusts exactly one public key; replacing it means those devices never accept
# another update. That is a decision for a person with a plan, not a script
# run by accident.
set -euo pipefail
cd "$(dirname "$0")/.."

DIR="$HOME/.scancart-signing"
KEY="$DIR/ota-signing-key.pem"
HEADER="src/ota/ota_public_key.h"

shopt -s nullglob
existing=("$DIR"/*.pem)
if [ "${#existing[@]}" -gt 0 ]; then
  echo "ota-keygen: a signing key already exists in $DIR; refusing to replace it." >&2
  echo "Devices in the field trust its public half; a new key would lock them out of updates." >&2
  exit 1
fi

mkdir -p "$DIR"
chmod 700 "$DIR"
( umask 077 && openssl ecparam -name prime256v1 -genkey -noout -out "$KEY" )
chmod 600 "$KEY"

PUB=$(openssl ec -in "$KEY" -pubout 2>/dev/null)
{
  cat <<'EOF'
#pragma once

/**
 * The public half of the firmware signing key. Generated by
 * `tools/ota-keygen.sh`; the private half never enters this repository.
 *
 * Publishing this is the point. A device trusts an image because it carries a
 * signature that only the private key can produce -- not because of where it
 * was downloaded from. That is what makes a poisoned DNS entry or a
 * compromised web server insufficient to install firmware here.
 *
 * Replacing this key means every device already in the field stops accepting
 * updates, so it is not a routine operation.
 */
#define OTA_PUBLIC_KEY_PEM \
EOF
  printf '%s\n' "$PUB" | sed 's/^/  "/; s/$/\\n" \\/' | sed '$ s/ \\$//'
} >"$HEADER"

echo "private key: $KEY (keep a backup somewhere offline)"
echo "public key:  $HEADER (commit this; the server copy in src/server/firmwareKey.ts must match)"
