#!/usr/bin/env bash
# Build, flash and test the firmware against a scan-home server.
#
#   SCAN_HOME_URL=https://scan-home-git-develop-....vercel.app \
#   VERCEL_BYPASS=<Protection Bypass for Automation secret> \
#   ./dev.sh flash usb
#
#   ./dev.sh build usb | flash usb | test | pio <args>
#
# SCAN_HOME_URL defaults to the develop preview. VERCEL_BYPASS is only needed
# while the preview sits behind Vercel deployment protection. Both are written
# to src/local_config.h, which git ignores and a production build refuses.
set -euo pipefail
cd "$(dirname "$0")"

DEFAULT_URL="https://scan-home-git-develop-shahaf-hadars-projects.vercel.app"

pio() {
  # Homebrew's Python refuses system-wide installs, so PlatformIO lives in a
  # venv next to the firmware. Nothing else has to know that.
  if [ ! -x .venv-pio/bin/pio ]; then
    echo "==> installing PlatformIO (once, a few minutes)"
    python3 -m venv .venv-pio
    ./.venv-pio/bin/pip install -q --upgrade pip
    # esptool imports intelhex without depending on it; without it every build
    # fails at the bootloader step with an unrelated-looking error.
    ./.venv-pio/bin/pip install -q platformio intelhex
  fi
  ./.venv-pio/bin/pio "$@"
}

write_config() {
  local url="${SCAN_HOME_URL:-$DEFAULT_URL}"
  # Written rather than passed as a flag: a string literal through the shell,
  # scons and the preprocessor needs escaping at every layer.
  {
    echo "// Generated by firmware/dev.sh - do not commit, do not edit."
    echo "#define SCANCART_HOST \"${url%/}\""
    if [ -n "${VERCEL_BYPASS:-}" ]; then
      echo "#define SCANCART_BYPASS \"$VERCEL_BYPASS\""
    fi
  } > src/local_config.h
  echo "==> firmware will talk to ${url%/}${VERCEL_BYPASS:+ (with the Vercel bypass header)}"
}

case "${1:-}" in
  build) write_config; pio run -e "${2:-usb}" ;;
  flash) write_config; pio run -e "${2:-usb}" -t upload -t monitor ;;
  test)  exec ./run-tests.sh ;;
  pio)   shift; pio "$@" ;;
  *) echo "usage: ./dev.sh build|flash [serial|uart|usb] | test | pio <args>"; exit 1 ;;
esac
